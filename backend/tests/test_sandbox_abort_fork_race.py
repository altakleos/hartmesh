"""A detached child can fork after abort captured its first /proc snapshot."""

from __future__ import annotations

import json
import os
import signal
import subprocess
import sys
import threading
import time
from pathlib import Path
from types import SimpleNamespace

import pytest

from deerflow.sandbox.local import local_sandbox
from deerflow.sandbox.local.local_sandbox import LocalSandbox
from deerflow.sandbox.sandbox import ABORT_TOKEN_ENV

pytestmark = pytest.mark.skipif(sys.platform != "linux", reason="requires Linux /proc process ownership")


def _race_probe(root: Path) -> dict:
    # Run in an isolated helper so only this fixture's orphans are adopted and
    # reaped; changing the pytest process's subreaper would affect other tests.
    import ctypes
    import shlex

    libc = ctypes.CDLL(None, use_errno=True)
    if libc.prctl(36, 1, 0, 0, 0) != 0:  # PR_SET_CHILD_SUBREAPER, no privileges needed
        raise OSError(ctypes.get_errno(), "cannot adopt fixture descendants")
    detached_file, child_file, spawn_file = (root / name for name in ("detached.pid", "child.pid", "spawn"))
    script = root / "detached.py"
    script.write_text(
        "import os, pathlib, subprocess, sys, time\n"
        "root = pathlib.Path(sys.argv[1])\n"
        "(root / 'detached.pid').write_text(str(os.getpid()))\n"
        "while not (root / 'spawn').exists():\n"
        "    time.sleep(0.001)\n"
        "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(300)'])\n"
        "(root / 'child.pid').write_text(str(child.pid))\n"
        "child.wait()\n",
        encoding="utf-8",
    )

    def wait_file(path):
        deadline = time.monotonic() + 5
        while time.monotonic() < deadline:
            try:
                value = path.read_text(encoding="utf-8").strip()
            except FileNotFoundError:
                value = ""
            if value:
                return value
            time.sleep(0.005)
        raise AssertionError(f"fixture marker never appeared: {path.name}")

    original_iterdir, original_popen = Path.iterdir, subprocess.Popen
    markers: set[bytes] = set()
    processes: list[subprocess.Popen] = []
    snapshots: list[set[int]] = []
    output, errors = [], []
    worker = None

    class TrackedPopen(original_popen):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            if token := (kwargs.get("env") or {}).get(ABORT_TOKEN_ENV):
                markers.add(f"{ABORT_TOKEN_ENV}={token}".encode())
                processes.append(self)

    def snapshot_then_fork(path):
        entries = list(original_iterdir(path))
        if path == Path("/proc"):
            snapshots.append({int(entry.name) for entry in entries if entry.name.isdigit()})
            if len(snapshots) == 1:
                # The late child must exist before production scans/kills its
                # parent, while remaining absent from the captured snapshot.
                spawn_file.touch()
                wait_file(child_file)
        return iter(entries)

    sandbox = LocalSandbox("abort-fork-race")

    def run_owned():
        try:
            command = f"setsid {shlex.quote(sys.executable)} {shlex.quote(str(script))} {shlex.quote(str(root))} & exec sleep 300"
            output.append(sandbox.execute_command(command, timeout=60))
        except BaseException as error:
            errors.append(type(error).__name__)

    try:
        subprocess.Popen = TrackedPopen
        worker = threading.Thread(target=run_owned, daemon=True)
        worker.start()
        wait_file(detached_file)
        deadline = time.monotonic() + 5
        registered = False
        while time.monotonic() < deadline:
            with sandbox._running_commands_lock:
                registered = len(sandbox._running_commands) == 1
            if registered:
                break
            time.sleep(0.005)
        assert registered, "the fixture command never registered for abort"
        Path.iterdir = snapshot_then_fork
        aborted = sandbox.abort_running_commands()
        child_pid = int(wait_file(child_file))
        worker.join(timeout=3)
        try:
            child_state = Path(f"/proc/{child_pid}/stat").read_text(encoding="utf-8").rpartition(")")[2].split()[0]
        except FileNotFoundError:
            child_state = None
        result = {
            "aborted": aborted,
            "late_child_excluded": child_pid not in snapshots[0],
            "child_running": child_state not in (None, "Z"),
            "worker_running": worker.is_alive(),
            "command_returned": len(output) == 1,
            "worker_errors": errors,
        }
    finally:
        Path.iterdir, subprocess.Popen = original_iterdir, original_popen
        # Even a failing regression kills only the exact markers generated by
        # this helper's Popen, then drains and reaps its own descendants.
        for _ in range(3):
            for entry in Path("/proc").iterdir():
                if not entry.name.isdigit() or int(entry.name) == os.getpid():
                    continue
                try:
                    if set((entry / "environ").read_bytes().split(b"\0")).isdisjoint(markers):
                        continue
                    os.kill(int(entry.name), signal.SIGKILL)
                except (OSError, ValueError):
                    pass
            time.sleep(0.01)
        if worker is not None:
            worker.join(timeout=3)
        for process in processes:
            process.wait(timeout=3)
        deadline = time.monotonic() + 3
        children_drained = False
        while time.monotonic() < deadline:
            try:
                pid, _ = os.waitpid(-1, os.WNOHANG)
            except ChildProcessError:
                children_drained = True
                break
            if not pid:
                time.sleep(0.01)
        assert worker is None or not worker.is_alive(), "fixture left its command worker alive"
        assert children_drained, "fixture left unreaped descendants"
    return result


def test_abort_kills_a_detached_child_forked_after_the_first_snapshot(tmp_path):
    helper = subprocess.Popen([sys.executable, str(Path(__file__).resolve()), str(tmp_path)], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    try:
        stdout, stderr = helper.communicate(timeout=20)
    finally:
        if helper.poll() is None:
            # Let the helper's finally drain its marked descendants before
            # treating a bounded test wait as failure.
            helper.terminate()
            try:
                helper.communicate(timeout=10)
            except subprocess.TimeoutExpired:
                helper.kill()
                helper.communicate()
    assert helper.returncode == 0, stderr
    result = json.loads(stdout)
    assert result["aborted"] == 1
    assert result["late_child_excluded"], "the fixture did not exercise the fork/snapshot ordering"
    assert not result["child_running"], "a child forked after enumeration survived the token sweep"
    assert not result["worker_running"], "the surviving child kept both output drains open"
    assert result["command_returned"] and not result["worker_errors"]


def test_abort_token_sweep_has_an_absolute_budget_even_with_many_processes(monkeypatch):
    entries = [Path(f"/proc/{pid}") for pid in range(1_000_000, 1_001_000)]
    marker = f"{ABORT_TOKEN_ENV}=owned".encode()
    now = 0.0
    killed = []

    def clock():
        nonlocal now
        now += 0.25
        return now

    monkeypatch.setattr(Path, "iterdir", lambda path: iter(entries))
    monkeypatch.setattr(Path, "read_bytes", lambda path: marker)
    monkeypatch.setattr(os, "kill", lambda pid, sig: killed.append(pid))
    monkeypatch.setattr(local_sandbox, "time", SimpleNamespace(monotonic=clock, sleep=lambda seconds: None), raising=False)
    LocalSandbox("t")._kill_processes_carrying_the_abort_tokens({"owned"})
    assert 0 < len(killed) < 20, "the deadline was not checked while scanning a large snapshot"


def test_repeated_token_sweep_keeps_self_and_unmarked_processes_safe(monkeypatch):
    own_pid = os.getpid()
    matched_pid, other_pid = own_pid + 1, own_pid + 2
    marker = f"{ABORT_TOKEN_ENV}=owned".encode()
    entries = [Path(f"/proc/{pid}") for pid in (own_pid, matched_pid, other_pid)]
    killed = []
    alive = True

    def environ(path):
        if path.parent.name in {str(own_pid), str(matched_pid)} and alive:
            return marker
        return marker + b"-not-the-same-token"

    def kill(pid, sig):
        nonlocal alive
        killed.append(pid)
        alive = False

    monkeypatch.setattr(Path, "iterdir", lambda path: iter(entries))
    monkeypatch.setattr(Path, "read_bytes", environ)
    monkeypatch.setattr(os, "kill", kill)
    LocalSandbox("t")._kill_processes_carrying_the_abort_tokens({"owned"})
    assert killed == [matched_pid]


def test_abort_token_sweep_caps_retries_for_a_persistent_match(monkeypatch):
    killed = []
    marker = f"{ABORT_TOKEN_ENV}=owned".encode()
    entry = Path(f"/proc/{os.getpid() + 1}")
    monkeypatch.setattr(Path, "iterdir", lambda path: iter([entry]))
    monkeypatch.setattr(Path, "read_bytes", lambda path: marker)
    monkeypatch.setattr(os, "kill", lambda pid, sig: killed.append(pid))
    monkeypatch.setattr(local_sandbox, "time", SimpleNamespace(monotonic=lambda: 0, sleep=lambda seconds: None))
    LocalSandbox("t")._kill_processes_carrying_the_abort_tokens({"owned"})
    assert 1 < len(killed) < 100, "persistent matches must neither stop rescanning immediately nor retry forever"


if __name__ == "__main__":

    def terminate_probe(signum, frame):
        raise TimeoutError("fixture helper was terminated")

    signal.signal(signal.SIGTERM, terminate_probe)
    print(json.dumps(_race_probe(Path(sys.argv[1])), sort_keys=True))
